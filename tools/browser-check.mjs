import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';

await mkdir('.cache', { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 1536, height: 1000 }, acceptDownloads: true });
const page = await context.newPage();
const errors = [], network = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', r => { if (/^https?:/.test(r.url())) { network.push(r.url()); } });
await context.route(/^https?:/, route => route.abort());
await page.goto(pathToFileURL(path.resolve('FFmpeg Command Forge.html')).href);
await page.getByRole('heading', { name: '从你的素材开始' }).waitFor();
await page.getByLabel('输入文件 1 路径').fill('D:\\Media\\演示素材.mp4');
await page.getByRole('button', { name: '输出', exact: true }).click();
await page.getByLabel('输出容器', { exact: true }).fill('mkv');
await page.getByRole('button', { name: '编码器', exact: true }).click();
await page.getByLabel('编码器 / 具体编码', { exact: true }).fill('libx264');
await page.getByLabel('编码器 / 编码预设', { exact: true }).fill('medium');
await page.getByRole('button', { name: '质量', exact: true }).click();
await page.getByLabel('比特率 / 控制方式', { exact: true }).selectOption('CRF');
await page.getByLabel('质量控制 / 值', { exact: true }).fill('23');
await page.getByRole('button', { name: '音频', exact: true }).click();
await page.getByLabel('编码器 / 代号', { exact: true }).fill('aac.native');
await page.getByLabel('比特率', { exact: true }).fill('192k');
await page.getByRole('button', { name: '任务与环境', exact: true }).click();
await page.getByRole('button', { name: '复制最终脚本 ↗' }).waitFor({ state: 'visible' });
await page.waitForFunction(() => !document.querySelector('#copy-final').disabled);
assert.match(await page.locator('#command').innerText(), /libx264/);
await page.screenshot({ path: '.cache/ui-desktop.png', fullPage: true });
const download = page.waitForEvent('download'); await page.getByRole('button', { name: '导出预设', exact: true }).click(); const file = await download; await file.saveAs('.cache/browser-preset.json');
await page.getByRole('button', { name: '画面', exact: true }).click();
await page.getByRole('textbox', { name: '搜索全部参数' }).fill('-pix_fmt');
await page.getByLabel('色彩管理 / 像素格式', { exact: true }).waitFor();
await page.getByRole('button', { name: '切换明暗主题' }).click();
await page.screenshot({ path: '.cache/ui-light.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole('button', { name: '任务与环境', exact: true }).click();
await page.screenshot({ path: '.cache/ui-mobile.png', fullPage: true });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, '移动端不应横向溢出');
await page.reload(); await page.getByLabel('输入文件 1 路径').waitFor(); assert.equal(await page.getByLabel('输入文件 1 路径').inputValue(), 'D:\\Media\\演示素材.mp4');
assert.deepEqual(errors, []); assert.deepEqual(network, []);
await context.close();
const blocked = await browser.newContext();
await blocked.addInitScript(() => { Object.defineProperty(window, 'localStorage', { get() { throw new Error('blocked'); } }); });
const blockedPage = await blocked.newPage(); await blockedPage.goto(pathToFileURL(path.resolve('FFmpeg Command Forge.html')).href); await blockedPage.getByRole('heading', { name: '从你的素材开始' }).waitFor(); await blocked.close();
await browser.close();
console.log('Edge 本地文件离线验收通过：参数编辑、预设导出、全局搜索、明暗主题、移动布局、工作区恢复、禁用存储；0 外部请求，0 页面错误。');
