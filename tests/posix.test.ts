import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, statSync, symlinkSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { buildPlan, defaultContext } from '../src/plan';
import { importPreset } from '../src/preset';
import { renderCommand, renderPlan } from '../src/render';
import type { Shell } from '../src/types';

test('POSIX 原生参数及实际转码', { skip: process.platform === 'win32' }, async () => {
  const values = ['', '中文 path', "single'quote", 'double"quote', 'tail\\', '\\\\server\\path', '$x $(echo nope)', '&|<>()^%!','line\nnext'];
  const shells: Shell[] = process.platform === 'darwin' ? ['bash', 'zsh'] : ['bash'];
  mkdirSync('.cache', { recursive: true }); const dir = mkdtempSync(path.resolve('.cache/posix-'));
  const run = (exe: string, args: string[]) => { const r = spawnSync(exe, args, { encoding: 'utf8', timeout: 30000, maxBuffer: 2e6 }); assert.equal(r.status, 0, (r.error?.message || '') + r.stderr); return r.stdout; };
  for (const shell of shells) {
    const stage = { executable: process.execPath, args: ['-e', 'console.log(JSON.stringify(process.argv.slice(1)))', '--', ...values], name: '', kind: 'single' as const, taskId: 'native', graph: '', maps: [] };
    assert.deepEqual(JSON.parse(run(shell, ['-c', renderCommand(stage, shell)])), values);
    const input = path.join(dir, `${shell} input\\中文 '引号.mp4`); run('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=160x90:rate=10', '-t', '1', '-c:v', 'libx264', input]);
    const c = defaultContext(); c.platform = process.platform === 'darwin' ? 'macos' : 'linux'; c.shell = shell;
    c.cwd = dir; c.inputs = [{ id: shell, path: path.basename(input) }]; c.outputDirectory = 'render';
    const occupied = path.join(dir, 'render', `${shell} clip20261106192344999.mkv`), output = path.join(dir, 'render', `${shell} clip20261106192345000.mkv`);
    const plan = await buildPlan(importPreset({ 输出容器: 'mkv', 输出_自动命名选项: '附加_2位结尾序号', 输出命名_替代文本: `${shell} clip20261106192344998`, 视频参数_编码器_具体编码: 'libx264', 视频参数_比特率_控制方式: 'TPE', 视频参数_比特率_基础: '200k', 输出命名_保留修改时间: true, 元数据_要写入的信息: [{ 字段: 'title', 值: occupied }, { 字段: 'comment', 值: '<OutputFile>' }] }), c);
    assert.equal(plan.status, 'ready', JSON.stringify(plan.issues));
    mkdirSync(path.dirname(occupied), { recursive: true });
    assert.equal(plan.tasks[0].output, occupied); writeFileSync(occupied, 'existing');
    run(shell, ['-c', renderPlan(plan).script]);
    assert.equal(readFileSync(occupied, 'utf8'), 'existing'); assert.ok(statSync(output).size > 100); assert.equal(statSync(output).mtimeMs, statSync(input).mtimeMs);
    const probe = JSON.parse(run('ffprobe', ['-v', 'error', '-show_format', '-show_streams', '-of', 'json', output]));
    assert.equal(probe.streams[0].codec_name, 'h264');
    assert.equal(probe.format.tags.title, occupied);
    assert.equal(probe.format.tags.COMMENT ?? probe.format.tags.comment, output);
    const copy = importPreset({ 视频参数_编码器_具体编码: 'copy' });
    c.inputs[0].output = output;
    run(shell, ['-c', renderPlan(await buildPlan(copy, c, undefined, true)).script]);
    assert.ok(statSync(output).size > 100);
    const original = readFileSync(input);
    const alias = path.join(dir, `${shell}-alias.mkv`);
    symlinkSync(input, alias);
    c.inputs[0].output = alias;
    const denied = spawnSync(shell, ['-c', renderPlan(await buildPlan(copy, c, undefined, true)).script], { encoding: 'utf8', timeout: 15000 });
    assert.ifError(denied.error);
    assert.notEqual(denied.status, 0);
    assert.deepEqual(readFileSync(input), original);
    delete c.inputs[0].output;
    c.inputs[0].subtitle = input.slice(0, -4) + '.srt';
    writeFileSync(c.inputs[0].subtitle, '1\n00:00:00,000 --> 00:00:01,000\n中文 subtitle\n');
    c.outputDirectory = 'special';
    const burn = await buildPlan(importPreset({ 输出容器: 'mkv', 输出_自动命名选项: 0, 视频参数_编码器_具体编码: 'libx264', 视频参数_烧录字幕_滤镜选择: 1, 视频参数_烧录字幕_字幕来源是外部文件: 1, 元数据_要写入的信息: [{ 字段: 'title', 值: '<InputFileName>' }] }), c);
    assert.equal(burn.status, 'ready', JSON.stringify(burn.issues));
    assert.equal(burn.tasks[0].output, path.join(dir, 'special', path.basename(input, '.mp4') + '.mkv'));
    run(shell, ['-c', renderPlan(burn).script]);
    const burned = JSON.parse(run('ffprobe', ['-v', 'error', '-show_format', '-of', 'json', burn.tasks[0].output]));
    assert.equal(burned.format.tags.title, path.basename(input));
    assert.deepEqual(readFileSync(input), original);
  }
});
